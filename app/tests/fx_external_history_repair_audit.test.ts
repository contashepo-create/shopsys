import { beforeEach, expect, it } from 'vitest'
import { EMPTY_EXTENDED, useDataStore, useRawDataStore } from '../src/data/repo.ts'
import { useAppStore } from '../src/stores/app.store.ts'
const initial = useRawDataStore.getState(), app = useAppStore.getState()
beforeEach(() => { useAppStore.setState({ ...app, setup: { ...app.setup, countryCode: 'EG', allowNegativeTreasury: true } }); useRawDataStore.setState({ ...initial, branches: [], activeBranchId: null, appUsers: [], currentUserId: null, items: [], suppliers: [], sales: [], vouchers: [], purchases: [], journal: [], fxConversions: [] }) })
const usd = { currencyCode: 'USD', amountMinor: 200, ratePpm: 10000000, decimals: 2 as const }
const receipt = () => useDataStore.getState().postVoucher({ kind: 'receipt', treasury: '1101', counterAccountCode: '4101', amountMinor: 2000, description: 'قبض', fx: usd, bookDecimals: 2, bookCurrencyCode: 'EGP' })
it('يستعيد ساق سند قبض مفقودة بإثبات دون المساس بالقيد', () => {
 const doc = receipt(), s = useDataStore.getState()
 useRawDataStore.setState(state => ({ vouchers: state.vouchers.map(row => ({ ...row, fx: null })) }))
 const before = useRawDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: doc.date.slice(0, 10), reason: 'الإيصال 123', confirmed: true })
 expect(useDataStore.getState().journal).toBe(before.journal)
 expect(s.getFxHoldings()[0]).toMatchObject({ currency: 'USD', amountMinor: 200, bookValueMinor: 2000 })
 expect(useDataStore.getState().vouchers[0].fxRepairHistory?.[0]).toMatchObject({ previousFx: null, fx: usd, reason: 'الإيصال 123' })
})
it('يستعيد ساق شراء بتكلفة حيازة مثبتة كما يقيدها القيد', () => {
 const incoming = receipt(), s = useDataStore.getState()
 s.addSupplier({ ...EMPTY_EXTENDED, nameAr: 'مورد', phone: '', notes: '' })
 const itemId = s.ensureServiceItemForFreeLine({ nameAr: 'صنف' })
 const fx = { ...usd, amountMinor: 100, ratePpm: 15000000 }
 const doc = s.postPurchase({ supplierId: useDataStore.getState().suppliers[0].id, date: incoming.date.slice(0, 10), lines: [{ itemId, qty: 1, unitPriceMinor: 3000 }], expenses: [], paidMinor: 1500, treasury: '1101', notes: '', fx, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ purchases: state.purchases.map(row => ({ ...row, fx: null })) }))
 const before = useRawDataStore.getState()
 s.repairExternalFx({ kind: 'purchase', id: doc.id, fx, date: doc.date.slice(0, 10), reason: 'إيصال سداد 123', confirmed: true })
 expect(s.getFxHoldings()[0]).toMatchObject({ amountMinor: 100, bookValueMinor: 1000 })
 expect(useDataStore.getState().journal).toBe(before.journal)
 expect(useDataStore.getState().purchases[0].fxRepairHistory?.[0]).toMatchObject({ previousFx: null, fx })
})
it('يصحح تاريخ مذكرة السند ويحتفظ بتاريخ السند واليومية', () => {
 const doc = receipt(), s = useDataStore.getState(), before = useRawDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'الإيصال', confirmed: true })
 expect(s.getFxFlows()[0].date).toBe('2026-01-01')
 expect(useDataStore.getState().vouchers[0].date).toBe(doc.date)
 expect(useDataStore.getState().journal).toBe(before.journal)
})
it('يرفض ساقاً مختلفة عن القيد أو دون إذن أو بسند معكوس بلا كتابة', () => {
 const doc = receipt(), s = useDataStore.getState(), before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: { ...usd, amountMinor: 100 }, date: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/قيمة|الدفتر/)
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: false })).toThrow(/تأكيد/)
 expect(useRawDataStore.getState().vouchers).toBe(before.vouchers)
 s.reverseVoucher(doc.id, 'تراجع')
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/معكوس/)
})
it('يحجب التقرير إذا حذف إثبات ساق سند أو جرى العبث بسجله', () => {
 const doc = receipt(), s = useDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })
 const saved = useRawDataStore.getState()
 useRawDataStore.setState({ vouchers: saved.vouchers.map(row => ({ ...row, fx: null })) })
 expect(() => s.getFxFlows()).toThrow(/مفقودة/)
 useRawDataStore.setState({ vouchers: saved.vouchers.map(row => ({ ...row, fxRepairHistory: row.fxRepairHistory?.map(h => ({ ...h, reason: '' })) })) })
 expect(() => s.getFxFlows()).toThrow(/سجل.*غير مطابق/)
})
it('لا يخمّن تكلفة شراء قديم إذا فقد إثبات التكلفة وكان القيد مختلفاً عن الاسمية', () => {
 const rec = receipt(), s = useDataStore.getState()
 s.addSupplier({ ...EMPTY_EXTENDED, nameAr: 'مورد', phone: '', notes: '' })
 const itemId = s.ensureServiceItemForFreeLine({ nameAr: 'صنف' }), fx = { ...usd, amountMinor: 100, ratePpm: 15000000 }
 const doc = s.postPurchase({ supplierId: useDataStore.getState().suppliers[0].id, date: rec.date.slice(0, 10), lines: [{ itemId, qty: 1, unitPriceMinor: 3000 }], expenses: [], paidMinor: 1500, treasury: '1101', notes: '', fx, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ purchases: state.purchases.map(row => ({ ...row, fx: null, fxOutBookValueMinor: undefined })) }))
 const before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'purchase', id: doc.id, fx, date: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 expect(useRawDataStore.getState().purchases).toBe(before.purchases)
})
it('يرفض تصحيح القبض إذا غيّر تكلفة صرف لاحق أو إذا تعارض التاريخ مع ترتيبه', () => {
 const doc = receipt(), s = useDataStore.getState()
 s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1000, description: 'صرف', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 const before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: { ...usd, amountMinor: 400, ratePpm: 5000000 }, date: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/تكاليف/)
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2099-01-01', reason: 'إيصال', confirmed: true })).toThrow(/تاريخ/)
 expect(useRawDataStore.getState().vouchers).toBe(before.vouchers)
})
it('يسجل سلسلتين متصلتين ويرفض العبث ثم يسمح بعكس السند السليم', () => {
 const doc = receipt(), s = useDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال أول', confirmed: true })
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-02', reason: 'إيصال ثان', confirmed: true })
 const saved = useRawDataStore.getState()
 expect(saved.vouchers[0].fxRepairHistory).toHaveLength(2)
 useRawDataStore.setState({ vouchers: saved.vouchers.map(row => ({ ...row, fxRepairHistory: row.fxRepairHistory?.map((h, i) => i === 1 ? { ...h, previousDate: '2025-01-01' } : h) })) })
 expect(() => s.getFxFlows()).toThrow(/سجل.*غير مطابق/)
 useRawDataStore.setState({ vouchers: saved.vouchers })
 s.reverseVoucher(doc.id, 'إلغاء موثق')
 expect(s.getFxFlows()).toEqual([])
})
it('لا يصلح الساق إذا اختفى القيد أو تكرر المستند', () => {
 const doc = receipt(), s = useDataStore.getState(), saved = useRawDataStore.getState()
 useRawDataStore.setState({ journal: [] })
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 useRawDataStore.setState({ journal: saved.journal, vouchers: [...saved.vouchers, { ...saved.vouchers[0] }] })
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/فريد/)
})
it('لا يعتمد قيداً فيه حركة إضافية على الخزينة أو فرق عملة زائد', () => {
 const doc = receipt(), s = useDataStore.getState(), saved = useRawDataStore.getState()
 useRawDataStore.setState({ journal: saved.journal.map(entry => entry.id !== doc.journalEntryId ? entry : { ...entry, lines: [...entry.lines, { accountCode: '1101', debit: 500, credit: 0 }, { accountCode: '4101', debit: 0, credit: 500 }] }) })
 const before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 expect(useRawDataStore.getState().vouchers).toBe(before.vouchers)
})
it('يتطلب صلاحية محاسبية وصلاحية الخزينة حتى لو قُدّم تأكيد', () => {
 const doc = receipt(), s = useDataStore.getState()
 useRawDataStore.setState({ appUsers: [{ id: 9, nameAr: 'كاشير', roleId: 'cashier', pinHash: 'x', active: true, treasuryAccess: { grants: [{ treasuryCode: '1101', operations: ['receipt'] }] } }] as never, currentUserId: 9 })
 const before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/صلاحية/)
 expect(useRawDataStore.getState().vouchers).toBe(before.vouchers)
})
it('يستعيد سند صرف بسعر مختلف عن تكلفة الرصيد دون تغيير فروق قيده ويظل قابلاً لإعادة التحميل', () => {
 const rec = receipt(), s = useDataStore.getState(), fx = { ...usd, amountMinor: 100, ratePpm: 15000000 }
 const doc = s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1500, description: 'صرف', fx, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ vouchers: state.vouchers.map(row => row.id === doc.id ? { ...row, fx: null } : row) }))
 const before = useRawDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx, date: rec.date.slice(0, 10), reason: 'إيصال صرف', confirmed: true })
 expect(useRawDataStore.getState().journal).toBe(before.journal)
 expect(s.getFxHoldings()[0]).toMatchObject({ amountMinor: 100, bookValueMinor: 1000 })
 const snapshot = JSON.parse(JSON.stringify({ vouchers: useRawDataStore.getState().vouchers, journal: useRawDataStore.getState().journal }))
 useRawDataStore.setState(snapshot)
 expect(s.getFxHoldings()[0]).toMatchObject({ amountMinor: 100, bookValueMinor: 1000 })
})
it('يحظر تحديث ساق مسجلة عند افتقاد صلاحية الصرف على الخزينة', () => {
 receipt(); const s = useDataStore.getState(), fx = { ...usd, amountMinor: 100 }
 const doc = s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1000, description: 'صرف', fx, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState({ appUsers: [{ id: 9, nameAr: 'محاسب', roleId: 'cashier', pinHash: 'x', active: true, extraPerms: ['acc.journal.reverse'], treasuryAccess: { grants: [{ treasuryCode: '1101', operations: ['receipt'] }] } }] as never, currentUserId: 9 })
 const before = useRawDataStore.getState()
 expect(() => s.repairExternalFx({ kind: 'voucher', id: doc.id, fx, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/خزينة|صلاحية|صرف/)
 expect(useRawDataStore.getState().vouchers).toBe(before.vouchers)
})
it('لا يخفي تاريخ إصلاح تالف إذا حُذفت ساق المستند', () => {
 const doc = receipt(), s = useDataStore.getState()
 s.repairExternalFx({ kind: 'voucher', id: doc.id, fx: usd, date: '2026-01-01', reason: 'إيصال', confirmed: true })
 useRawDataStore.setState(state => ({ vouchers: state.vouchers.map(row => ({ ...row, fx: null, fxRepairHistory: {} as never })) }))
 expect(() => s.getFxFlows()).toThrow(/سجل.*غير مطابق|مفقودة/)
})
