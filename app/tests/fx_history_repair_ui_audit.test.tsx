import { afterEach, expect, it } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { FxTreasuryTab } from '../src/ui/pages/FxTreasuryTab.tsx'
import { useDataStore, useRawDataStore } from '../src/data/repo.ts'
import { useAppStore } from '../src/stores/app.store.ts'
const initial = useRawDataStore.getState(), app = useAppStore.getState()
afterEach(() => { cleanup(); useRawDataStore.setState(initial); useAppStore.setState(app) })
it('يستعيد ساق قبض مفقودة من تقرير العملة بإثبات صريح ثم يصحح تاريخ المذكرة', () => {
 useAppStore.setState({ ...app, setup: { ...app.setup, countryCode: 'EG', allowNegativeTreasury: true }, fxRates: {} })
 useRawDataStore.setState({ ...initial, branches: [], activeBranchId: null, appUsers: [], currentUserId: null, sales: [], purchases: [], vouchers: [], journal: [], fxConversions: [], items: [] })
 const s = useDataStore.getState(), id = s.ensureServiceItemForFreeLine({ nameAr: 'خدمة' })
 const doc = s.postSale({ lines: [{ itemId: id, nameAr: 'خدمة', qty: 1, unitPriceMinor: 2000, unitCostMinor: 0, discountPercent: 0, soldByWeight: false }], customerId: null, payment: 'cash', treasury: '1101', paidMinor: 2000, invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 render(<FxTreasuryTab cur={{ code: 'EGP', symbol: 'ج.م', decimals: 2, name: 'جنيه' }} companyName="متجر" />)
 fireEvent.click(screen.getByText('مطابقة إيصال قبض تاريخي'))
 fireEvent.change(screen.getByLabelText('فاتورة القبض التاريخي'), { target: { value: String(doc.id) } })
 fireEvent.change(screen.getByLabelText('تاريخ القبض المثبت'), { target: { value: doc.date.slice(0, 10) } })
 fireEvent.change(screen.getByLabelText('مبلغ الساق المستعادة'), { target: { value: '2' } })
 fireEvent.change(screen.getByLabelText('سعر الساق المستعادة'), { target: { value: '10' } })
 fireEvent.change(screen.getByLabelText('مرجع مطابقة القبض'), { target: { value: 'إيصال 123' } })
 fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.click(screen.getByRole('button', { name: /حفظ مطابقة القبض/ }))
 expect(useDataStore.getState().sales[0].fx?.currencyCode).toBe('USD')
 fireEvent.change(screen.getByLabelText('فاتورة القبض التاريخي'), { target: { value: String(doc.id) } })
 fireEvent.change(screen.getByLabelText('تاريخ القبض المثبت'), { target: { value: '2026-01-01' } })
 fireEvent.change(screen.getByLabelText('مرجع مطابقة القبض'), { target: { value: 'إيصال 123' } })
 fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.click(screen.getByRole('button', { name: /حفظ مطابقة القبض/ }))
 expect(s.getFxFlows()[0].date).toBe('2026-01-01')
 expect(useDataStore.getState().sales[0].date).toBe(doc.date)
})
it('تظل أداة مطابقة الإيصال متاحة عندما تحجب ساق تالفة التقرير', () => {
 useAppStore.setState({ ...app, setup: { ...app.setup, countryCode: 'EG', allowNegativeTreasury: true }, fxRates: {} })
 useRawDataStore.setState({ ...initial, branches: [], activeBranchId: null, appUsers: [], currentUserId: null, sales: [], purchases: [], vouchers: [], journal: [], fxConversions: [], items: [] })
 const s = useDataStore.getState(), id = s.ensureServiceItemForFreeLine({ nameAr: 'خدمة' })
 const doc = s.postSale({ lines: [{ itemId: id, nameAr: 'خدمة', qty: 1, unitPriceMinor: 2000, unitCostMinor: 0, discountPercent: 0, soldByWeight: false }], customerId: null, payment: 'cash', treasury: '1101', paidMinor: 2000, invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false, fx: { currencyCode: 'USD', amountMinor: 200, ratePpm: 10000000, decimals: 2 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: { ...row.fx!, amountMinor: 999 } })) }))
 render(<FxTreasuryTab cur={{ code: 'EGP', symbol: 'ج.م', decimals: 2, name: 'جنيه' }} companyName="متجر" />)
 expect(screen.getByRole('alert').textContent).toContain('تعذر عرض تقرير العملات')
 fireEvent.click(screen.getByText('مطابقة إيصال قبض تاريخي'))
 fireEvent.change(screen.getByLabelText('فاتورة القبض التاريخي'), { target: { value: String(doc.id) } })
 fireEvent.change(screen.getByLabelText('تاريخ القبض المثبت'), { target: { value: doc.date.slice(0, 10) } })
 fireEvent.change(screen.getByLabelText('مبلغ الساق المستعادة'), { target: { value: '2' } })
 fireEvent.change(screen.getByLabelText('سعر الساق المستعادة'), { target: { value: '10' } })
 fireEvent.change(screen.getByLabelText('مرجع مطابقة القبض'), { target: { value: 'إيصال 777' } })
 fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.click(screen.getByRole('button', { name: /حفظ مطابقة القبض/ }))
 expect(screen.queryByRole('alert')).toBeNull()
 expect(s.getFxHoldings()[0].amountMinor).toBe(200)
})
