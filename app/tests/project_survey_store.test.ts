import { afterEach, beforeEach, expect, it } from 'vitest'
import { EMPTY_EXTENDED, useDataStore, useRawDataStore } from '../src/data/repo.ts'
import { useAppStore } from '../src/stores/app.store.ts'
const original = useRawDataStore.getState(), app = useAppStore.getState(), S = () => useRawDataStore.getState()
beforeEach(() => {
 useAppStore.setState({ ...app, setup: { ...app.setup, countryCode: 'EG', activityId: 'contracting', modules: ['contracting'] } as never })
 useRawDataStore.setState({ ...original, branches: [], activeBranchId: null, currentUserId: null, customers: [], projects: [], boqItems: [], projectSurveys: [], projectExtracts: [], clientAdvances: [], journal: [], vouchers: [], clientSettlements: [], approvalRequests: [], changeOrders: [], projectDeletionRecords: [] } as never)
})
afterEach(() => { useRawDataStore.setState(original); useAppStore.setState(app) })
function setup() {
 S().addCustomer({ ...EMPTY_EXTENDED, nameAr: 'عميل', phone: '', creditLimitMinor: 0, notes: '' })
 const p = S().addProject({ nameAr: 'مشروع', clientName: 'عميل', clientId: S().customers[0].id, contractValueMinor: 100000, retentionPercent: 0, startDate: '2026-01-01', notes: '' })
 const b = S().addBoqItem({ projectId: p.id, code: '1', descriptionAr: 'عمل', unit: 'م', qty: 1000, unitPriceMinor: 100 })
 return { p, b }
}
const extract = (projectId: number, boqItemId: number, cumulativeQty: number, isFinal = false) => S().addProjectExtract({ projectId, vatPercent: 0, payment: 'credit', description: 'أعمال', isFinal, extractQtyLines: [{ boqItemId, cumulativeQty }] })
it('الحصر المعتمد يبقى مستقلاً دون مراجعة جديدة عند المستخلص', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 856 }], expectedRevision: 0, reason: '', isFinal: false })
 extract(p.id, b.id, 200)
 expect(S().projectSurveys).toHaveLength(1)
 expect(S().projectSurveys[0].lines[0].cumulativeQty).toBe(856)
 expect(S().projectSurveys[0].revisions).toHaveLength(1)
 expect(S().projectSurveys[0].revisions[0].source).toBe('manual')
 expect(S().projectSurveys[0].id).toBe(p.id)
})
it('المستخلص الكمي لا ينشئ أو يحدّث الحصر', () => {
 const { p, b } = setup()
 extract(p.id, b.id, 200)
 const final = extract(p.id, b.id, 1000, true)
 expect(final.totals.grossMinor).toBe(80000)
 expect(S().projectSurveys).toHaveLength(0)
})
it('يمنع الختامي مع بقاء كميات محصورة غير مستخلصة دون قيد', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 856 }], expectedRevision: 0, reason: '', isFinal: true })
 const before = S()
 expect(() => extract(p.id, b.id, 200, true)).toThrow(/مساواة/)
 expect(S().journal).toBe(before.journal)
 expect(S().projectSurveys).toBe(before.projectSurveys)
})
it('يرفض تعديل الحصر المتقادم والتخفيض غير الموثق مع بقائه مستقلاً عن المستخلص', () => {
 const { p, b } = setup()
 extract(p.id, b.id, 200)
 const save = (qty: number, expectedRevision: number, reason = '') => S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: qty }], expectedRevision, reason, isFinal: false })
 save(500, 0)
 expect(() => save(300, 0)).toThrow(/تغير الحصر/)
 expect(() => save(300, 1)).toThrow(/سبب/)
 expect(save(100, 1, 'تصحيح قياس').lines[0].cumulativeQty).toBe(100)
})
it('يحذف الحصر فقط مع مشروع لم يرحّل أي مستند مالي', async () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 useRawDataStore.setState({ ownerPinHash: 'dd963634ae8f2839313302f03077c41b6de321c73056d69b1f34334c193c425e' })
 await S().deleteUnpostedProject(p.id, 'إلغاء العميل', undefined, '123456')
 expect(S().projectSurveys).toHaveLength(0)
 expect(S().journal).toHaveLength(0)
})
it('يمكن تسجيل حصر يدوي مستقل حتى مع مستخلص إجمالي قديم', () => {
 const { p, b } = setup()
 S().addProjectExtract({ projectId: p.id, description: 'قديم', payment: 'credit', vatPercent: 0, grossMinor: 1000 })
 expect(S().projectSurveys).toHaveLength(0)
 expect(S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 200 }], expectedRevision: 0, reason: '', isFinal: false }).lines[0].cumulativeQty).toBe(200)
})
it('عزل الفرع: لا يظهر حصر مشروع فرع آخر', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 const branches = [{ id: 1, nameAr: 'رئيسي', isMain: true, warehouseId: 1, treasuryCode: '1101', active: true }, { id: 2, nameAr: 'ثان', isMain: false, warehouseId: 2, treasuryCode: '1102', active: true }]
 useRawDataStore.setState({ branches: branches as never, activeBranchId: 2, projects: S().projects.map(row => ({ ...row, branchId: 1 })) as never, projectSurveys: S().projectSurveys.map(row => ({ ...row, branchId: 1 })) as never })
 expect(useDataStore.getState().projectSurveys).toHaveLength(0)
 expect(() => S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 200 }], expectedRevision: 1, reason: '', isFinal: false })).toThrow(/الفرع/)
})
it('يحفظ لقطات العقد ويرفض تغييرها أو حذف بند له حصر', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 expect(S().projectSurveys[0].lines[0]).toMatchObject({ contractQty: 1000, unitPriceMinor: 100, unit: 'م' })
 expect(() => S().updateBoqItem(b.id, { qty: 900 })).toThrow(/حصر/)
 expect(() => S().removeBoqItem(b.id)).toThrow(/حصر/)
})
it('تعديل مستخلص كمي لا يغير الحصر المستقل', () => {
 const { p, b } = setup()
 const ex = extract(p.id, b.id, 200)
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 500 }], expectedRevision: 0, reason: '', isFinal: false })
 const revised = S().editProjectExtract({ extractId: ex.id, description: 'تصحيح', payment: 'credit', vatPercent: 0, reason: 'تصحيح القياس', extractQtyLines: [{ boqItemId: b.id, cumulativeQty: 250 }] })
 expect(revised.lines?.[0].newExecutedQty).toBe(250)
 expect(S().projectSurveys[0].lines[0].cumulativeQty).toBe(500)
 expect(S().projectSurveys[0].revisions).toHaveLength(1)
})
it('لا يغير المراجعة عند اعتماد مستخلص إجمالي سابق النمط', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 const before = S()
 S().addProjectExtract({ projectId: p.id, description: '', payment: 'credit', vatPercent: 0, grossMinor: 100 })
 expect(S().projectSurveys).toBe(before.projectSurveys)
 expect(S().journal).toHaveLength(1)
})
it('المسودة المحفوظة بلا قيد، وترحيلها يمحوها ذرّياً، والمتقادمة تُرفض', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 856 }], expectedRevision: 0, reason: '', isFinal: true })
 const draft = S().prepareProjectExtractDraft(p.id, 1)
 expect(draft.lines).toEqual([{ boqItemId: b.id, cumulativeQty: 856 }])
 expect(S().journal).toHaveLength(0)
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 800 }], expectedRevision: 1, reason: 'تصحيح', isFinal: true })
 expect(() => S().assertProjectExtractDraftCurrent(p.id)).toThrow(/متقادمة/)
 expect(() => S().addProjectExtract({ projectId: p.id, description: '', payment: 'credit', vatPercent: 0, extractQtyLines: draft.lines, sourceSurveyDraft: true })).toThrow(/متقادمة/)
 const next = S().prepareProjectExtractDraft(p.id, 2)
 expect(() => S().addProjectExtract({ projectId: p.id, description: '', payment: 'credit', vatPercent: 0, extractQtyLines: next.lines, sourceSurveyDraft: true, isFinal: true })).toThrow(/مساواة/)
 S().addProjectExtract({ projectId: p.id, description: '', payment: 'credit', vatPercent: 0, extractQtyLines: next.lines, sourceSurveyDraft: true })
 expect(S().projectExtractDrafts).toHaveLength(0)
 expect(S().projectExtracts).toHaveLength(1)
 expect(S().journal).toHaveLength(1)
})
it('حذف المسودة غير المرحّلة لا يغيّر الحصر أو الدفتر', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 S().prepareProjectExtractDraft(p.id, 1)
 expect(() => S().deleteProjectExtractDraft(p.id, '')).toThrow(/سبب/)
 S().deleteProjectExtractDraft(p.id, 'مسودة ملغاة')
 expect(S().projectExtractDrafts).toHaveLength(0)
 expect(S().projectSurveys).toHaveLength(1)
 expect(S().journal).toHaveLength(0)
})
it('حذف الحصر ومسودته غير المرحّلة بسبب لا يمس المشروع أو الدفتر', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 S().prepareProjectExtractDraft(p.id, 1)
 expect(() => S().deleteUnpostedSurvey(p.id, '')).toThrow(/سبب/)
 S().deleteUnpostedSurvey(p.id, 'إلغاء الحصر')
 expect(S().projectSurveys).toHaveLength(0)
 expect(S().projectExtractDrafts).toHaveLength(0)
 expect(S().projects).toHaveLength(1)
 expect(S().journal).toHaveLength(0)
})
it('يمنع حذف حصر مرتبط بمستخلص مرحّل دون أي تغيير في القيد', () => {
 const { p, b } = setup()
 S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })
 extract(p.id, b.id, 200)
 const before = S()
 expect(() => S().deleteUnpostedSurvey(p.id, 'إلغاء')).toThrow(/مرتبط/)
 expect(S().projectSurveys).toBe(before.projectSurveys)
 expect(S().journal).toBe(before.journal)
})
it('يمنع حذف عرض المشروع عند وجود مستخلص مالي ويحفظ العرض والدفتر', () => {
 const { p, b } = setup()
 const quote = S().addQuotation({ kind: 'quotation', clientName: 'عميل', clientId: p.clientId, titleAr: 'عرض', validUntil: '2027-01-01', lines: [{ descriptionAr: 'أعمال', qty: 1, unitAr: 'م', unitPriceMinor: 100, vatPercent: 0 }], notes: '' })
 useRawDataStore.setState({ quotations: [{ ...quote, projectId: p.id }] })
 extract(p.id, b.id, 200)
 const before = S()
 expect(() => S().deleteQuotation(quote.id, p.id, 'إلغاء')).toThrow(/مرتبط/)
 expect(S().quotations).toBe(before.quotations)
 expect(S().journal).toBe(before.journal)
})
it('إعادة الحصر بعد الحذف تستعمل هوية جديدة وتحفظ سجل الحذف', () => {
 const { p, b } = setup()
 const args = { projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false }
 const first = S().saveProjectSurvey(args)
 S().deleteUnpostedSurvey(p.id, 'إلغاء')
 const second = S().saveProjectSurvey(args)
 expect(second.id).not.toBe(first.id)
 expect(S().surveyDeletionRecords[0].id).toBe(first.id)
})

it('يرفض الحصر والمستخلص إذا احتوى مشروع على بند مؤرخ صراحة لفرع آخر حتى في عرض كل الفروع', () => {
 const { p, b } = setup()
 const branches = [{ id: 1, nameAr: 'رئيسي', isMain: true, warehouseId: 1, treasuryCode: '1101', active: true }, { id: 2, nameAr: 'ثان', isMain: false, warehouseId: 2, treasuryCode: '1102', active: true }]
 useRawDataStore.setState({ branches: branches as never, activeBranchId: null, projects: S().projects.map(row => ({ ...row, branchId: 1 })) as never, customers: S().customers.map(row => ({ ...row, branchId: 1 })) as never, boqItems: S().boqItems.map(row => ({ ...row, branchId: 2 })) as never })
 const before = S()
 expect(() => S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })).toThrow(/فرع/)
 expect(() => extract(p.id, b.id, 100)).toThrow(/فرع/)
 expect(S().projectSurveys).toBe(before.projectSurveys)
 expect(S().projectExtracts).toBe(before.projectExtracts)
 expect(S().journal).toBe(before.journal)
})

it.each(['boqItems', 'projectSurveys', 'projectExtractDrafts', 'changeOrders'] as const)('يرفض مستند المشروع الموسوم بفرع آخر (%s) دون أي قيد', collection => {
 const { p, b } = setup()
 const branches = [{ id: 1, nameAr: 'رئيسي', isMain: true, warehouseId: 1, treasuryCode: '1101', active: true }, { id: 2, nameAr: 'ثان', isMain: false, warehouseId: 2, treasuryCode: '1102', active: true }]
 const foreign = collection === 'boqItems' ? { boqItems: [{ ...b, branchId: 2 }] } : collection === 'projectSurveys' ? { projectSurveys: [{ id: 10, projectId: p.id, branchId: 2, lines: [], revisions: [] }] } : collection === 'projectExtractDrafts' ? { projectExtractDrafts: [{ id: 10, projectId: p.id, branchId: 2 }] } : { changeOrders: [{ id: 10, projectId: p.id, branchId: 2, amountMinor: 100000, status: 'approved' }] }
 useRawDataStore.setState({ ...foreign, branches: branches as never, activeBranchId: 1, projects: S().projects.map(row => ({ ...row, branchId: 1 })) as never, customers: S().customers.map(row => ({ ...row, branchId: 1 })) as never } as never)
 const before = S()
 expect(() => S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false })).toThrow(/فرع آخر/)
 expect(() => extract(p.id, b.id, 100)).toThrow(/فرع آخر/)
 expect(S().journal).toBe(before.journal); expect(S().projectExtracts).toBe(before.projectExtracts)
})
it('يسمح ببند قديم بلا فرع صريح إذا ارتبط بمشروع الفرع', () => {
 const { p, b } = setup()
 const branches = [{ id: 1, nameAr: 'رئيسي', isMain: true, warehouseId: 1, treasuryCode: '1101', active: true }, { id: 2, nameAr: 'ثان', isMain: false, warehouseId: 2, treasuryCode: '1102', active: true }]
 useRawDataStore.setState({ branches: branches as never, activeBranchId: 1, projects: S().projects.map(row => ({ ...row, branchId: 1 })) as never, customers: S().customers.map(row => ({ ...row, branchId: 1 })) as never })
 expect(S().saveProjectSurvey({ projectId: p.id, lines: [{ boqItemId: b.id, cumulativeQty: 100 }], expectedRevision: 0, reason: '', isFinal: false }).lines[0].cumulativeQty).toBe(100)
})
