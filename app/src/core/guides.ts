/** موضوعات نشاط بعينه + العامة (النشاط أولاً) */
export function guidesForActivity(activityId: string | null): GuideTopic[] {
  const own = (activityId && ACTIVITY_GUIDES[activityId]) || []
  return [...own, ...COMMON_GUIDES]
}

/** بحث نصي بسيط في العناوين والفقرات */
export function searchGuides(topics: GuideTopic[], query: string): GuideTopic[] {
  const q = query.trim()
  if (!q) return topics
  return topics.filter((t) => t.titleAr.includes(q) || t.paragraphsAr.some((p) => p.includes(q)))
}
