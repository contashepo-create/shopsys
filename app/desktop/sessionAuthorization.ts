import { createHash, pbkdf2Sync, timingSafeEqual } from 'node:crypto'
import { PIN_MAX_LENGTH, PIN_MIN_LENGTH } from '../src/core/auth.ts'
import { isInAppNavigation } from './navigationPolicy.ts'

export interface DesktopAuthState {
  ownerPinHash?: unknown
  ownerTempPin?: { pinHash?: unknown; expiresAt?: unknown } | null
  appUsers?: unknown
}

export function persistedAuthState(payloadJson: string | null): DesktopAuthState | null {
  if (!payloadJson) return null
  try {
    const parsed: unknown = JSON.parse(payloadJson)
    if (!parsed || typeof parsed !== 'object') return null
    const wrapped = parsed as { state?: unknown }
    const state = wrapped.state && typeof wrapped.state === 'object' ? wrapped.state : parsed
    return state as DesktopAuthState
  } catch {
    return null
  }
}

export function hasConfiguredDesktopAuth(state: DesktopAuthState | null): boolean {
  if (!state) return false
  const users = Array.isArray(state.appUsers) ? state.appUsers : []
  return (typeof state.ownerPinHash === 'string' && state.ownerPinHash.length > 0)
    || users.some((user) => !!user && typeof user === 'object' && (user as { active?: unknown }).active === true)
}

/** Verify the same PBKDF2-SHA256 / legacy SHA-256 formats as core/audit.ts. */
export function verifyDesktopPin(pin: unknown, encoded: unknown): boolean {
  if (typeof pin !== 'string' || typeof encoded !== 'string') return false
  const clean = pin.trim()
  if (clean.length < PIN_MIN_LENGTH || clean.length > PIN_MAX_LENGTH) return false
  const modern = /^pbkdf2-sha256\$(\d{5,8})\$([0-9a-f]{32})\$([0-9a-f]{64})$/i.exec(encoded)
  let actual: Buffer
  let expected: Buffer
  if (modern) {
    const iterations = Number(modern[1])
    // Persisted hashes are generated by the app (currently 310k); cap hostile/corrupt values to avoid CPU DoS.
    if (iterations < 50_000 || iterations > 2_000_000) return false
    actual = pbkdf2Sync(Buffer.from(`tahakam:${clean}`), Buffer.from(modern[2], 'hex'), iterations, 32, 'sha256')
    expected = Buffer.from(modern[3], 'hex')
  } else {
    if (!/^[0-9a-f]{64}$/i.test(encoded)) return false
    actual = createHash('sha256').update(`tahakam:${clean}`).digest()
    expected = Buffer.from(encoded, 'hex')
  }
  return actual.length === expected.length && timingSafeEqual(actual, expected)
}

export function authorizeDesktopIdentity(state: DesktopAuthState | null, userId: unknown, pin: unknown, now = Date.now()): boolean {
  if (!hasConfiguredDesktopAuth(state)) return true
  if (!state || typeof pin !== 'string') return false
  if (userId == null) {
    if (verifyDesktopPin(pin, state.ownerPinHash)) return true
    const temp = state.ownerTempPin
    return !!temp && typeof temp.pinHash === 'string' && typeof temp.expiresAt === 'string'
      && Number.isFinite(Date.parse(temp.expiresAt)) && now < Date.parse(temp.expiresAt)
      && verifyDesktopPin(pin, temp.pinHash)
  }
  if (typeof userId !== 'number' || !Number.isSafeInteger(userId) || !Array.isArray(state.appUsers)) return false
  const user = state.appUsers.find((row) => !!row && typeof row === 'object' && (row as { id?: unknown }).id === userId) as { active?: unknown; pinHash?: unknown } | undefined
  return !!user && user.active === true && verifyDesktopPin(pin, user.pinHash)
}

export function isAuthorizedDesktopSender(authRequired: boolean, authorizedIds: ReadonlySet<number>, senderId: number): boolean {
  return !authRequired || authorizedIds.has(senderId)
}

/**
 * Snapshot IPC is needed during login hydration, so it cannot be PIN-gated yet.
 * Keep that bootstrap exception within known app windows, the app's own URL, and
 * the two persistence stores; never let an arbitrary/preload-bearing renderer
 * enumerate any snapshot row by choosing a store name.
 */
export function canReadDesktopSnapshot(input: {
  senderId: number
  knownWindowIds: ReadonlySet<number>
  senderUrl: string
  appIndexFileUrl: string
  devOrigin: string | null
  storeName: unknown
}): boolean {
  return input.knownWindowIds.has(input.senderId)
    && isInAppNavigation(input.senderUrl, input.appIndexFileUrl, input.devOrigin)
    && (input.storeName === 'shopsys-data' || input.storeName === 'shopsys-app')
}
