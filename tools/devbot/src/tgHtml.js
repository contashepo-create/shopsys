/**
 * تهريب HTML لرسائل تليجرام — مركز التحكم كله يرسل بـ`parse_mode: 'HTML'`.
 * ───────────────────────────────────────────────────────────────────────────
 * لماذا وحدة مستقلة: `cleanText` في أماكن متفرقة ينزع `<` و`>` (فيمنع الوسوم) لكنه
 * **لا يهرّب `&`** — وتليجرام في وضع HTML يرفض الرسالة كلها بخطأ
 * «Can't parse entities» إذا وجد تسلسلاً مثل `&quot` أو `&#` داخل نص. النتيجة
 * العملية قبل هذا الإصلاح: محل اسمه «A&B» أو رسالة دعم فيها `&` ⇒ **رسالة
 * المطوّر تفشل بصمت** (الاستثناء مبتلع) فلا يصله بلاغ العميل الجديد ولا يقرأ
 * محادثة الدعم — أي أن بند 2 وبند 1 يتعطلان لعملاء بعينهم بلا أي أثر.
 *
 * القاعدة: **الوسوم يبنيها الكود، والقيم يهرّبها هذا التابع.** لا تُمرَّر رسالة
 * كاملة إلى هنا (سيُهرَّب `<b>` المقصود)، بل كل قيمة مُدرجة داخل النص.
 *
 * يُستعمل من `worker.js` و`adminPanel.js` و`registrations.js` و`subscriptions.js`
 * ⇒ وحدة مستقلة بلا استيراد منها (درس الاستيراد الدائري في هذا المجلد).
 */

/** تهريب قيمة واحدة لعرضها داخل رسالة HTML — لا ترمي استثناءً أبداً */
export function tgEscape(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
}

/** اختصار مريح للحقول الاختيارية: الفارغ يعود فارغاً (لا «undefined») */
export function tgField(value) {
  const text = tgEscape(value)
  return text === '' ? '' : text
}
