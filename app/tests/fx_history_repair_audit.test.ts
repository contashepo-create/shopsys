import { beforeEach, expect, it } from 'vitest'
import { useDataStore, useRawDataStore } from '../src/data/repo.ts'
import { useAppStore } from '../src/stores/app.store.ts'
const initial = useRawDataStore.getState(), app = useAppStore.getState()
beforeEach(() => { useAppStore.setState({ ...app, setup: { ...app.setup, countryCode: 'EG', allowNegativeTreasury: true, allowNegativeStock: true } }); useRawDataStore.setState({ ...initial, branches: [], activeBranchId: null, customers: [], items: [], sales: [], vouchers: [], purchases: [], journal: [], fxConversions: [] }) })
const usd = { currencyCode: 'USD', amountMinor: 200, ratePpm: 10000000, decimals: 2 as const }
function sale() {
 const s = useDataStore.getState(), itemId = s.ensureServiceItemForFreeLine({ nameAr: 'خدمة' })
 return { s, doc: s.postSale({ lines: [{ itemId, nameAr: 'خدمة', qty: 1, unitPriceMinor: 2000, unitCostMinor: 0, discountPercent: 0, soldByWeight: false }], customerId: null, payment: 'cash', treasury: '1101', paidMinor: 2000, invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false, fx: usd, bookDecimals: 2, bookCurrencyCode: 'EGP' }) }
}
it('يثبت ساق قبض مفقودة بإيصال صريح دون تعديل القيد', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => row.id === doc.id ? { ...row, fx: null } : row) }))
 const before = useRawDataStore.getState()
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'الإيصال 123', confirmed: false })).toThrow(/تأكيد/)
 s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'الإيصال 123', confirmed: true })
 const state = useDataStore.getState()
 expect(state.journal).toBe(before.journal)
 expect(state.sales[0].fxReconstructionEvidence).toMatchObject({ reason: 'الإيصال 123', fx: usd, journalEntryId: doc.journalEntryId })
 expect(s.getFxHoldings()).toEqual([expect.objectContaining({ currency: 'USD', amountMinor: 200, bookValueMinor: 2000 })])
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })) }))
 expect(() => s.getFxFlows()).toThrow(/مفقودة/)
})
it('يرفض ساقاً مستعادة بقيمة مختلفة أو قيد غير مثبت بلا أثر', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })) }))
 const before = useRawDataStore.getState()
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 300 }, receiptDate: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/الدفتر/)
 useRawDataStore.setState({ journal: [] })
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يصحح تاريخ حركة قبض البيع المذكرية مع حفظ تاريخ الفاتورة والقيد', () => {
 const { s, doc } = sale(), before = useRawDataStore.getState()
 s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'تاريخ الإيصال 123', confirmed: true })
 const after = useDataStore.getState()
 expect(after.sales[0].date).toBe(doc.date)
 expect(after.journal).toBe(before.journal)
 expect(s.getFxFlows()[0].date).toBe('2026-01-01')
 expect(after.sales[0].fxMemoDateHistory?.[0]).toMatchObject({ reason: 'تاريخ الإيصال 123', correctedDate: '2026-01-01', journalEntryId: doc.journalEntryId })
})
it('يرفض تاريخاً يغيّر ترتيب حركة سابقة أو لاحقة للعملة نفسها', () => {
 const { s, doc } = sale()
 s.postVoucher({ kind: 'receipt', treasury: '1101', counterAccountCode: '4101', amountMinor: 1000, description: 'تحصيل لاحق', date: '2026-02-01', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 const before = useRawDataStore.getState()
 expect(() => s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-03-01', reason: 'إيصال', confirmed: true })).toThrow(/ترتيب|لاحقة/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يصحح الساق رغم قبض لاحق إذا ظلت كل الأرصدة وتكاليف الخروج مثبتة', () => {
 const { s, doc } = sale()
 s.postVoucher({ kind: 'receipt', treasury: '1101', counterAccountCode: '4101', amountMinor: 1000, description: 'تحصيل لاحق', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 s.correctSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 100, ratePpm: 20000000 }, reason: 'إيصال فعلي', confirmed: true })
 expect(s.getFxHoldings()).toEqual([expect.objectContaining({ currency: 'USD', amountMinor: 200, bookValueMinor: 3000 })])
})
it('يرفض تعديل الساق إن تغيرت تكلفة حركة صرف لاحقة', () => {
 const { s, doc } = sale()
 s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1000, description: 'صرف', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 const before = useRawDataStore.getState()
 expect(() => s.correctSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 100, ratePpm: 20000000 }, reason: 'إيصال فعلي', confirmed: true })).toThrow(/لاحقة/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يحجب تلاعب سجل تاريخ القبض واستعادة الساق', () => {
 const { s, doc } = sale()
 s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال', confirmed: true })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fxMemoDateHistory: row.fxMemoDateHistory?.map(h => ({ ...h, journalEntryId: 999 })) })) }))
 expect(() => s.getFxFlows()).toThrow(/تاريخ.*غير مطابق/)
})
it('يستبدل ساقاً تاريخية تالفة بإيصال موثق ويحتفظ بالقيم التالفة دون مس القيد', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: { ...usd, amountMinor: 999 } })) }))
 expect(() => s.getFxFlows()).toThrow(/لا تطابق/)
 const before = useRawDataStore.getState()
 s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'إيصال أصلي 777', confirmed: true })
 const after = useDataStore.getState()
 expect(after.sales[0].fxReconstructionEvidence).toMatchObject({ previousFx: { ...usd, amountMinor: 999 }, fx: usd })
 expect(after.journal).toBe(before.journal)
 expect(s.getFxHoldings()).toEqual([expect.objectContaining({ currency: 'USD', amountMinor: 200, bookValueMinor: 2000 })])
})
it('يرفض إصلاح سجل العملة بواسطة كاشير لا يملك صلاحية عكس القيود', () => {
 const { s, doc } = sale()
 useRawDataStore.setState({ appUsers: [{ id: 9, nameAr: 'كاشير', roleId: 'cashier', pinHash: 'x', active: true, treasuryAccess: { grants: [{ treasuryCode: '1101', operations: ['receipt'] }] } }] as never, currentUserId: 9 })
 const before = useRawDataStore.getState()
 expect(() => s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/صلاحية/)
 expect(() => s.correctSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 100, ratePpm: 20000000 }, reason: 'إيصال', confirmed: true })).toThrow(/صلاحية/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يستعيد الساق وتاريخ الإيصال معاً حين يكون تاريخ المستند مفقوداً ويحفظ الأصل', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, date: '', fx: null })) }))
 const before = useRawDataStore.getState()
 s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: '2026-01-15', reason: 'إيصال 777', confirmed: true })
 expect(s.getFxFlows()[0].date).toBe('2026-01-15')
 expect(useDataStore.getState().sales[0].date).toBe('')
 expect(useDataStore.getState().sales[0].fxMemoDateHistory?.[0]).toMatchObject({ previousDate: null, documentDate: '', correctedDate: '2026-01-15' })
 expect(useDataStore.getState().journal).toBe(before.journal)
})
it('يعيد ساقاً مفقودة تتبعها حركة صرف مثبتة عندما تتطابق تكلفة كل حركة', () => {
 const { s, doc } = sale()
 s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1000, description: 'صرف', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })) }))
 expect(() => s.getFxHoldings()).toThrow(/غير مثبت/)
 s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })
 expect(s.getFxHoldings()).toEqual([expect.objectContaining({ currency: 'USD', amountMinor: 100, bookValueMinor: 1000 })])
})
it('يرفض استعادة الساق إذا غيرت تكلفة حركة صرف لاحقة مسجلة', () => {
 const { s, doc } = sale()
 s.postVoucher({ kind: 'payment', treasury: '1101', counterAccountCode: '5108', amountMinor: 1000, description: 'صرف', fx: { ...usd, amountMinor: 100 }, bookDecimals: 2, bookCurrencyCode: 'EGP' })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })) }))
 const before = useRawDataStore.getState()
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 100, ratePpm: 20000000 }, receiptDate: doc.date.slice(0, 10), reason: 'إيصال', confirmed: true })).toThrow(/تكاليف/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يسمح لمستخدم مخوّل بعكس القيود ولديه صلاحية القبض على الخزينة', () => {
 const { s, doc } = sale()
 useRawDataStore.setState({ appUsers: [{ id: 9, nameAr: 'محاسب', roleId: 'cashier', pinHash: 'x', active: true, extraPerms: ['acc.journal.reverse'], treasuryAccess: { grants: [{ treasuryCode: '1101', operations: ['receipt'] }] } }] as never, currentUserId: 9 })
 s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال محاسبي', confirmed: true })
 expect(s.getFxFlows()[0].date).toBe('2026-01-01')
})
it('يحجب التلاعب بتاريخ إيصال الساق المستعادة بعد الحفظ', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })) }))
 s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: '2026-01-01', reason: 'إيصال', confirmed: true })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fxReconstructionEvidence: { ...row.fxReconstructionEvidence!, receiptDate: '2026-02-01' } })) }))
 expect(() => s.getFxFlows()).toThrow(/تاريخ.*غير مطابق/)
})
it('لا يعيد بناء ساق قبض بيع من قيد متزن يحوي حركة خزينة إضافية غير مثبتة', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null })), journal: state.journal.map(entry => entry.id !== doc.journalEntryId ? entry : { ...entry, lines: [...entry.lines, { accountCode: '1101', debit: 500, credit: 0 }, { accountCode: '4101', debit: 0, credit: 500 }] }) }))
 const before = useRawDataStore.getState()
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'الإيصال', confirmed: true })).toThrow(/قيد/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('لا يصحح تاريخ أو ساق بيع حين يحتوي القيد حركة إضافية على الخزينة', () => {
 const { s, doc } = sale()
 useRawDataStore.setState(state => ({ journal: state.journal.map(entry => entry.id !== doc.journalEntryId ? entry : { ...entry, lines: [...entry.lines, { accountCode: '1101', debit: 500, credit: 0 }, { accountCode: '4101', debit: 0, credit: 500 }] }) }))
 const before = useRawDataStore.getState()
 expect(() => s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 expect(() => s.correctSaleFx({ saleId: doc.id, fx: { ...usd, amountMinor: 100, ratePpm: 20000000 }, reason: 'إيصال', confirmed: true })).toThrow(/قيد/)
 expect(useRawDataStore.getState().sales).toBe(before.sales)
})
it('يحجب الساق المصححة إذا أضيفت حركة خزينة إلى قيدها بعد الإصلاح', () => {
 const { s, doc } = sale()
 s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال', confirmed: true })
 useRawDataStore.setState(state => ({ journal: state.journal.map(entry => entry.id !== doc.journalEntryId ? entry : { ...entry, lines: [...entry.lines, { accountCode: '1101', debit: 500, credit: 0 }, { accountCode: '4101', debit: 0, credit: 500 }] }) }))
 expect(() => s.getFxFlows()).toThrow(/قيد/)
})
it('لا يخفي سجل تصحيح بيع تالف إذا فقدت الساق، ولا يستبدله بإثبات جديد', () => {
 const { s, doc } = sale()
 s.correctSaleFxMemoDate({ saleId: doc.id, date: '2026-01-01', reason: 'إيصال', confirmed: true })
 useRawDataStore.setState(state => ({ sales: state.sales.map(row => ({ ...row, fx: null, fxMemoDateHistory: {} as never })) }))
 expect(() => s.getFxFlows()).toThrow(/سجل|تالف/)
 expect(() => s.reconstructSaleFx({ saleId: doc.id, fx: usd, receiptDate: doc.date.slice(0, 10), reason: 'إيصال آخر', confirmed: true })).toThrow(/سجل|تالف/)
})
