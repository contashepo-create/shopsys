import { beforeEach, expect, it } from 'vitest'
import { useDataStore, useRawDataStore } from '../src/data/repo.ts'
import { useAppStore } from '../src/stores/app.store.ts'
const initial = useRawDataStore.getState(), app = useAppStore.getState()
const line = { itemId: 1, nameAr: 'دواء', qty: 3, unitPriceMinor: 2000, unitCostMinor: 1000, discountPercent: 0, soldByWeight: false }
beforeEach(() => {
 useAppStore.getState().setActiveBranchContext(null)
 useAppStore.setState({ setup: { ...app.setup, countryCode: 'EG', allowNegativeTreasury: true } })
 useRawDataStore.setState({ ...initial, branches: [], activeBranchId: null, items: [{ id: 1, nameAr: 'دواء', sku: 'D', barcodes: [], categoryId: 1, baseUnit: 'قطعة', extraUnits: [], costMinor: 1000, stockValueMinor: 10000, stockQty: 10, priceMinor: 2000, minQty: 0, isActive: true, trackExpiry: true }] as never, warehouses: [{ id: 1, nameAr: 'رئيسي', isMain: true }] as never, transfers: [], purchases: [], sales: [], saleReturns: [], journal: [], batches: [{ id: 1, itemId: 1, qty: 2, expiryDate: '2099-01-01', purchaseId: 1, receivedAt: '2026-01-01', warehouseId: 1 }, { id: 2, itemId: 1, qty: 8, expiryDate: '2099-02-01', purchaseId: 2, receivedAt: '2026-01-02', warehouseId: 1 }] })
})
it('يثبت دفعات البيع المصروفة حتى لو استنفدت وحذفت من الرصيد، مع نسخة مقابلة في القيد', () => {
 const sale = useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 expect(sale.saleExpiryBatches?.map(b => [b.id, b.qty])).toEqual([[1, 2], [2, 1]])
 expect(useRawDataStore.getState().journal.find(e => e.id === sale.journalEntryId)?.saleExpiryBatches).toEqual(sale.saleExpiryBatches)
 expect(useRawDataStore.getState().batches.map(b => [b.id, b.qty])).toEqual([[2, 7]])
})
it('لا يرحل بيعا مع معرف دفعة مكرر حتى لو كان التكرار لصنف آخر', () => {
 const state = useRawDataStore.getState()
 useRawDataStore.setState({ batches: [...state.batches, { ...state.batches[0], itemId: 99 }] })
 const before = useRawDataStore.getState()
 expect(() => useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })).toThrow(/دفعة/)
 const after = useRawDataStore.getState()
 expect(after.sales).toBe(before.sales)
 expect(after.journal).toBe(before.journal)
 expect(after.batches).toBe(before.batches)
})
it('لا يحوّل كمية غير متتبعة إلى دفعة مختلقة، ولا يشارك نفس الكائن بين البيع والقيد', () => {
 const state = useRawDataStore.getState()
 useRawDataStore.setState({ batches: [{ ...state.batches[0], qty: 1 }] })
 const sale = useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 const proof = useRawDataStore.getState().journal.find(e => e.id === sale.journalEntryId)!.saleExpiryBatches!
 expect(sale.saleExpiryBatches?.map(b => b.qty)).toEqual([1])
 expect(proof).toEqual(sale.saleExpiryBatches)
 expect(proof).not.toBe(sale.saleExpiryBatches)
 expect(proof[0]).not.toBe(sale.saleExpiryBatches![0])
})
it('يظل تعديل فاتورة الدفعات محجوباً حتى إذا أوقف تتبع الصلاحية للصنف لاحقاً', () => {
 const sale = useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 const state = useRawDataStore.getState()
 useRawDataStore.setState({ items: state.items.map(i => ({ ...i, trackExpiry: false })) })
 expect(() => useDataStore.getState().editSale({ saleId: sale.id, lines: [line], customerId: null, payment: 'cash', paidMinor: 6000, treasury: '1101', invoiceDiscountPercent: 0, reason: 'تعديل', einvoiceActive: false })).toThrow(/الصلاحية/)
})
it('لا يسمح بتجاوز حارس مرتجع الدفعة بتعطيل صلاحية الصنف بعد البيع', () => {
 const s = useDataStore.getState(), sale = s.postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 useRawDataStore.setState({ items: useRawDataStore.getState().items.map(i => ({ ...i, trackExpiry: false })) })
 const before = useRawDataStore.getState()
 expect(() => s.postSaleReturn({ saleId: sale.id, qtyByItem: new Map([[1, 1]]), refund: 'cash', reason: 'رد' })).toThrow(/دفعة/)
 expect(useRawDataStore.getState().journal).toBe(before.journal)
})
it('يحفظ دفعات البيع موزعة على المخازن المصدرة لها', () => {
 useRawDataStore.setState({ warehouses: [{ id: 1, nameAr: 'رئيسي', isMain: true }, { id: 2, nameAr: 'فرعي', isMain: false }] as never, transfers: [{ id: 1, transferNumber: 'T', date: '2026-01-01', fromWarehouseId: 1, toWarehouseId: 2, lines: [{ itemId: 1, qty: 5, nameAr: 'دواء' }], totalQty: 5, notes: '' }], batches: [{ id: 1, itemId: 1, qty: 5, expiryDate: '2099-01-01', purchaseId: null, receivedAt: '2026-01-01', warehouseId: 1 }, { id: 2, itemId: 1, qty: 5, expiryDate: '2099-02-01', purchaseId: null, receivedAt: '2026-01-01', warehouseId: 2 }] })
 const sale = useDataStore.getState().postSale({ lines: [{ ...line, qty: 1, warehouseId: 1 }, { ...line, qty: 3, warehouseId: 2 }], warehouseId: 1, customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 expect(sale.saleExpiryBatches?.map(b => [b.id, b.warehouseId, b.qty])).toEqual([[1, 1, 1], [2, 2, 3]])
})
it('يبقى إثبات الدفعات على البيع والقيد بعد النسخة الاحتياطية والاستعادة', async () => {
 const { flushSecureStorageWrites, secureStorage } = await import('../src/data/secureStorage.ts')
 const { buildBackup, parseBackup } = await import('../src/core/backup.ts')
 const sale = useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 await flushSecureStorageWrites('shopsys-data')
 const stored = await secureStorage.getItem('shopsys-data')
 const backup = buildBackup({ appState: {}, storeState: JSON.parse(stored!), appDataVersion: 1, shopName: 'اختبار' })
 const restored = parseBackup(JSON.stringify(backup))
 useRawDataStore.setState({ sales: [], journal: [] })
 await flushSecureStorageWrites('shopsys-data')
 await secureStorage.setItem('shopsys-data', JSON.stringify(restored.data.store))
 await useRawDataStore.persist.rehydrate()
 const current = useRawDataStore.getState()
 expect(current.sales.find(s => s.id === sale.id)?.saleExpiryBatches).toEqual(sale.saleExpiryBatches)
 expect(current.journal.find(e => e.id === sale.journalEntryId)?.saleExpiryBatches).toEqual(sale.saleExpiryBatches)
})
it('يعيد كمية الدفعة المحددة صراحة ويمنع تجاوز المتبقي منها', () => {
 const s = useDataStore.getState()
 const sale = s.postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 const ret = s.postSaleReturn({ saleId: sale.id, lineSpecs: [{ lineIndex: 0, qty: 1, condition: 'resellable', batchAllocations: [{ batchId: 1, qty: 1 }] }], refund: 'cash', reason: 'استلام دفعة' })
 let current = useRawDataStore.getState()
 expect(current.batches.find(b => b.id === 1)?.qty).toBe(1)
 expect(current.items[0].stockQty).toBe(8)
 expect(ret.lines[0].expiryBatchAllocations).toEqual([{ batchId: 1, qty: 1 }])
 const before = current
 expect(() => s.postSaleReturn({ saleId: sale.id, lineSpecs: [{ lineIndex: 0, qty: 2, condition: 'resellable', batchAllocations: [{ batchId: 1, qty: 2 }] }], refund: 'cash', reason: 'رد زائد' })).toThrow(/دفعة|كمية/)
 current = useRawDataStore.getState()
 expect(current.journal).toBe(before.journal)
 expect(current.batches).toBe(before.batches)
})
const post = () => useDataStore.getState().postSale({ lines: [line], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
const spec = (id: number, qty: number, condition: 'resellable' | 'damaged' = 'resellable') => [{ lineIndex: 0, qty, condition, batchAllocations: [{ batchId: id, qty }] }]
const ret = (saleId: number, lineSpecs: ReturnLineSpecForTest) => useDataStore.getState().postSaleReturn({ saleId, lineSpecs, refund: 'cash', reason: 'فحص' })
type ReturnLineSpecForTest = { lineIndex: number; qty: number; condition: 'resellable' | 'damaged'; batchAllocations?: { batchId: number; qty: number }[]; warehouseId?: number }[]
it('يرفض دليلاً متعارضاً بين البيع والقيد دون أثر', () => {
 const sale = post()
 useRawDataStore.setState({ journal: useRawDataStore.getState().journal.map(e => e.id === sale.journalEntryId ? { ...e, saleExpiryBatches: e.saleExpiryBatches?.map(b => ({ ...b, expiryDate: '2099-12-31' })) } : e) })
 const before = useRawDataStore.getState()
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
 expect(useRawDataStore.getState().journal).toBe(before.journal)
})
it('يرفض رداً بعد تالف سابق مجهول الدفعة', () => {
 const sale = post()
 ret(sale.id, [{ lineIndex: 0, qty: 1, condition: 'damaged' }])
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
})
it('يستهلك التالف المحدد من رصيد الدفعة القابل للرد ولا يدخل المخزون', () => {
 const sale = post(), before = useRawDataStore.getState()
 ret(sale.id, spec(1, 1, 'damaged'))
 expect(useRawDataStore.getState().batches).toBe(before.batches)
 ret(sale.id, spec(1, 1))
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة|كمية/)
 expect(useRawDataStore.getState().batches.find(b => b.id === 1)?.qty).toBe(1)
})
it('يرفض العبث بإثبات المرتجع السابق بالقيد', () => {
 const sale = post(); ret(sale.id, spec(1, 1))
 const current = useRawDataStore.getState(), last = current.saleReturns[0]
 useRawDataStore.setState({ journal: current.journal.map(e => e.id === last.journalEntryId ? { ...e, saleReturnExpiryBatches: [] } : e) })
 const before = useRawDataStore.getState()
 expect(() => ret(sale.id, spec(2, 1))).toThrow(/دفعة/)
 expect(useRawDataStore.getState().batches).toBe(before.batches)
})
it('يحافظ على الدفعة المستنفدة عند إعادة استخدام رقمها لدفعة أخرى', () => {
 const sale = post(), current = useRawDataStore.getState()
 useRawDataStore.setState({ batches: [...current.batches, { ...current.batches[0], id: 1, expiryDate: '2099-12-30' }] })
 ret(sale.id, spec(1, 1))
 const batches = useRawDataStore.getState().batches
 expect(batches.find(b => b.id === 1)?.expiryDate).toBe('2099-12-30')
 expect(batches.find(b => b.expiryDate === '2099-01-01')?.qty).toBe(1)
 expect(batches.find(b => b.expiryDate === '2099-01-01')?.id).not.toBe(1)
})
it('يرفض نقل مرتجع الصلاحية إلى مخزن مختلف قبل دعم الحركة', () => {
 const sale = post()
 useRawDataStore.setState({ warehouses: [...useRawDataStore.getState().warehouses, { id: 2, nameAr: 'ثان', isMain: false } as never] })
 expect(() => ret(sale.id, [{ ...spec(1, 1)[0], warehouseId: 2 }])).toThrow(/مخزن/)
})
it('يقبل تقسيم الوحدة الكبرى على أكثر من دفعة بوحدتها الأساسية', () => {
 const sale = useDataStore.getState().postSale({ lines: [{ ...line, qty: 1, unitFactor: 3, unitPriceMinor: 6000, unitCostMinor: 3000 }], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 ret(sale.id, [{ lineIndex: 0, qty: 1, condition: 'resellable', batchAllocations: [{ batchId: 1, qty: 2 }, { batchId: 2, qty: 1 }] }])
 expect(useRawDataStore.getState().items[0].stockQty).toBe(10)
 expect(useRawDataStore.getState().batches.map(b => [b.id, b.qty]).sort()).toEqual([[1, 2], [2, 8]])
})
it('يرفض سجلاً لم يتتبع كل الكمية المباعة بدفعات', () => {
 const state = useRawDataStore.getState()
 useRawDataStore.setState({ batches: [{ ...state.batches[0], qty: 1 }] })
 const sale = post()
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
})
it('لا يتجاوز حارس الكمية غير المتتبعة عند تعطيل الصلاحية لاحقاً', () => {
 useRawDataStore.setState({ batches: [] })
 const sale = post()
 expect(sale.saleExpiryItemIds).toEqual([1])
 useRawDataStore.setState({ items: useRawDataStore.getState().items.map(i => ({ ...i, trackExpiry: false })) })
 expect(() => useDataStore.getState().postSaleReturn({ saleId: sale.id, qtyByItem: new Map([[1, 1]]), refund: 'cash', reason: 'رد' })).toThrow(/دفعة/)
})
it('لا يتجاوز الحارس بحذف دليل البيع مع بقاء دليل القيد وتعطيل الصلاحية', () => {
 const sale = post(), state = useRawDataStore.getState()
 useRawDataStore.setState({ items: state.items.map(i => ({ ...i, trackExpiry: false })), sales: state.sales.map(s => ({ ...s, saleExpiryBatches: undefined, saleExpiryItemIds: undefined })) })
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
})
it('لا يدخل المخزون إن تغير الصنف إلى تتبع السيريال بعد البيع', () => {
 const sale = post()
 useRawDataStore.setState({ items: useRawDataStore.getState().items.map(i => ({ ...i, trackSerial: true })) })
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
})
it('يوحد هوية الدفعة مع اختلاف null وغياب رقم التشغيلة بدلاً من تكرار الرصيد', () => {
 const sale = post(), state = useRawDataStore.getState()
 useRawDataStore.setState({ batches: [...state.batches, { ...sale.saleExpiryBatches![0], id: 7, lotNumber: null, qty: 1 }] })
 ret(sale.id, spec(1, 1))
 const batches = useRawDataStore.getState().batches.filter(b => b.expiryDate === '2099-01-01')
 expect(batches).toHaveLength(1)
 expect(batches[0].id).toBe(7)
 expect(batches[0].qty).toBe(2)
})
it('يرفض تكرار سطر الصنف ببيع واحد لأن توزيع الدفعات على السطور غير مثبت', () => {
 const sale = useDataStore.getState().postSale({ lines: [{ ...line, qty: 1 }, { ...line, qty: 2 }], customerId: null, payment: 'cash', invoiceDiscountPercent: 0, taxPercent: 0, taxInclusive: false })
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة/)
})
it('يرفض كمية دفعة تتجاوز دقة المخزون أو لا تطابق المرتجع', () => {
 const sale = post(), before = useRawDataStore.getState()
 expect(() => ret(sale.id, [{ ...spec(1, 1)[0], batchAllocations: [{ batchId: 1, qty: 1.0004 }] }])).toThrow(/كمية/)
 expect(() => ret(sale.id, [{ ...spec(1, 1)[0], batchAllocations: [{ batchId: 1, qty: 0.5 }] }])).toThrow(/دفعة/)
 expect(useRawDataStore.getState().batches).toBe(before.batches)
})
it('يبقى توزيع المرتجع السابق قابلاً للمطابقة بعد نسخة احتياطية فعلية واستعادتها', async () => {
 const { flushSecureStorageWrites, secureStorage } = await import('../src/data/secureStorage.ts')
 const { buildBackup, parseBackup } = await import('../src/core/backup.ts')
 const sale = post(); ret(sale.id, spec(1, 1, 'damaged'))
 await flushSecureStorageWrites('shopsys-data')
 const saved = await secureStorage.getItem('shopsys-data')
 const backup = parseBackup(JSON.stringify(buildBackup({ appState: {}, storeState: JSON.parse(saved!), appDataVersion: 1, shopName: 'اختبار' })))
 useRawDataStore.setState({ sales: [], journal: [], saleReturns: [], batches: [] })
 await flushSecureStorageWrites('shopsys-data')
 await secureStorage.setItem('shopsys-data', JSON.stringify(backup.data.store))
 await useRawDataStore.persist.rehydrate()
 ret(sale.id, spec(1, 1))
 expect(useDataStore.getState().batches.find(b => b.expiryDate === '2099-01-01')?.qty).toBe(1)
 expect(() => ret(sale.id, spec(1, 1))).toThrow(/دفعة|كمية/)
})
